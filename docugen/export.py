"""Writing an assembled Document out as a .docx file.

python-docx is used directly rather than through a .docx template file, because
the document structure we need is simple - a title, a subtitle and a flat list
of numbered sections - and generating it in code keeps everything about the
output visible in one place.

to_docx_bytes returns bytes rather than writing to disk so that the Streamlit
download button can serve the file straight to the browser, and so the tests
never have to clean up temporary files.
"""

from __future__ import annotations

import io

from docx import Document as DocxDocument
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

from docugen.assembly import Document

DISCLAIMER = (
    "This document was generated by DocuGenAI from a standard template. "
    "It is a drafting aid, not legal advice, and must be reviewed by a qualified "
    "professional before it is signed or relied upon."
)


def to_docx_bytes(document: Document) -> bytes:
    docx = DocxDocument()
    _set_base_font(docx)

    heading = docx.add_heading(document.title, level=0)
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER

    if document.subtitle:
        subtitle = docx.add_paragraph(document.subtitle)
        subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
        subtitle.runs[0].italic = True

    for block in document.blocks:
        if block.kind == "heading":
            docx.add_heading(block.text, level=1)
        else:
            docx.add_paragraph(block.text)

    docx.add_page_break()
    note = docx.add_paragraph(DISCLAIMER)
    note.runs[0].italic = True
    note.runs[0].font.size = Pt(9)

    buffer = io.BytesIO()
    docx.save(buffer)
    return buffer.getvalue()


def suggested_filename(document: Document) -> str:
    safe = "".join(ch if ch.isalnum() or ch in " -_" else "" for ch in document.title)
    return f"{safe.strip().replace(' ', '_').lower() or 'document'}.docx"


def _set_base_font(docx) -> None:
    style = docx.styles["Normal"]
    style.font.name = "Georgia"
    style.font.size = Pt(11)
